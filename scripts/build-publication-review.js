#!/usr/bin/env node
// scripts/build-publication-review.js — writes api/_lib/seasonal-editorial/MIGRATION_REVIEW.md: the publication
// migration review for the 14 entries that were "published" on feature/halloween-completion (7e094df) under the older
// gate: their current evidence, publication status under the five-state gate, and what is still outstanding.
// Derived from entries.json by the same gate the public page uses; nothing is hand-written or hand-set.
//   node scripts/build-publication-review.js          write
//   node scripts/build-publication-review.js --check  exit 1 if stale
"use strict";
const fs = require("fs");
const path = require("path");
const ED = require("../api/_lib/seasonal-editorial/editorial.js");
const OUT = path.join(ED.DIR, "MIGRATION_REVIEW.md");

function build() {
  const all = ED.entries(), rows = [];
  for (const slug of ED.COLLECTIONS.ORDER) for (const e of all[slug]) if (e.migration) rows.push({ slug, e, rv: ED.review(e) });
  const out = [];
  out.push("# Publication migration review: the 14 entries that were public on feature/halloween-completion");
  out.push("");
  out.push("Generated by `node scripts/build-publication-review.js` from `entries.json`. Do not edit by hand. Private: this file lives in `api/_lib/seasonal-editorial/` and is not served.");
  out.push("");
  out.push("**What changed.** On `feature/halloween-completion` (7e094df) these 14 entries had `status: \"published\"` under the older, weaker gate (inventory entry plus independent web coverage; no official-site read; no recorded approval). Under the five-state gate an entry is public only when every item is recorded, including an explicit approval by the approving person. These entries are **preserved as records** with their evidence, image and history. They are **not grandfathered** as fully verified, and nothing here adds an approval. `main` never contained these pages, so no live URL changes.");
  out.push("");
  out.push("**Result:** public destinations after migration = " + rows.filter((r) => ED.COLLECTIONS.isPublic(r.e)).length + " of " + rows.length + ". A migrated record is public only through an approval recorded by the approving person; none is public by migration alone.");
  out.push("");
  const count = {};
  rows.forEach((r) => { count[r.rv.state] = (count[r.rv.state] || 0) + 1; });
  out.push("State counts: " + ED.COLLECTIONS.STATES.map((s) => s + " " + (count[s] || 0)).join(", ") + ".");
  out.push("");
  out.push("| Collection | Entry | Was | Now (derived) | Image route | Rights route | Still needed |");
  out.push("|---|---|---|---|---|---|---|");
  for (const { slug, e, rv } of rows) {
    out.push("| " + slug + " | " + e.name + " | published | " + rv.state + " | " + (rv.imageRoute || "none (generated card)") + " | " + (rv.rightsRoute || "none") + " | " +
      (rv.outstanding.map((o) => { const m = /^Gate (\d)/.exec(o); return m ? m[1] : null; }).filter(Boolean).join(", ") || "none") + " |");
  }
  out.push("");
  out.push("Numbers in the last column are gate items: 1 official-source verification, 2 relevance, 3 image, 4 image rights, 5 explicit approval.");
  for (const { slug, e, rv } of rows) {
    out.push("");
    out.push("## " + e.name + " (" + slug + ", `" + e.id + "`)");
    out.push("");
    out.push("- Previous: `published` on " + e.migration.legacyBranch + " " + e.migration.legacyCommit + ". Basis: " + e.migration.legacyBasis + ".");
    out.push("- Now: declared `" + e.status + "`, derived `" + rv.state + "`. Public: " + (ED.COLLECTIONS.isPublic(e) ? "yes" : "no") + ".");
    out.push("- Evidence on file:");
    (e.evidence || []).forEach((x) => out.push("  - " + x.level + (x.websiteChecked ? " (site read " + x.checkedAt + ")" : "") + ": " + x.note + (x.url ? " <" + x.url + ">" : "")));
    out.push("- Relevance: " + (e.relevance ? (e.relevance.confirmed ? "confirmed " + e.relevance.checkedAt + " by " + e.relevance.checkedBy + ": " + e.relevance.note : "not confirmed") : "not recorded") + ".");
    const im = e.image;
    out.push("- Image: `" + im.src + "`" + (im.ownerPhoto ? " (owner photo " + im.ownerPhoto.photoId + ", sha256 " + im.acquired.sha256.slice(0, 12) + "..., verified " + im.ownerPhoto.verifiedAt + ")" : im.remote ? " (generated card; linked image " + im.remote.src + " recorded as the default)" : " (generated illustrative card)") + ".");
    out.push("- Outstanding:");
    if (!rv.outstanding.length) out.push("  - nothing blocks the gate except what is listed under caveats.");
    rv.outstanding.forEach((o) => out.push("  - " + o));
    if (rv.caveats.length) { out.push("- Caveats:"); rv.caveats.forEach((o) => out.push("  - " + o)); }
  }
  out.push("");
  return out.join("\n");
}
module.exports = { build, OUT };
if (require.main === module) {
  const text = build();
  if (process.argv.includes("--check")) { if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== text) { console.error("stale: MIGRATION_REVIEW.md"); process.exit(1); } }
  else fs.writeFileSync(OUT, text);
}
