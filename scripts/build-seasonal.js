// Gate item 3, file half. EVERY record that carries an acquired image (published or not) must have its file on disk
// matching the size, sha256 and pixel size recorded in image.acquired; the generated cards, alternates and the
// placeholder it falls back to must exist; and an owner-photo record must match the private photo library
// (library id, same card file, original identifiers present). A URL or a recorded license without a downloaded,
// validated file does not pass.
function validateAssets(all) {
  const problems = [];
  all = all || ED.entries();
  const lib = ED.read("photo-library.json");
  const photos = Object.fromEntries(lib.destination_specific.concat(lib.editorial_atmospheric).map((p) => [p.id, p]));
  const exists = (rel) => fs.existsSync(path.join(root, rel));
  for (const slug of Object.keys(all)) {
    for (const e of all[slug]) {
      const where = slug + "/" + e.id, im = e.image || {};
      for (const u of [im.src].concat(im.alternates || [], im.placeholder ? [im.placeholder] : [])) {
        if (u && /^\//.test(u) && !exists(u)) problems.push(where + ": image file missing " + u);
      }
      const a = im.acquired;
      if (!a) { if (e.status === "PUBLISHED" && !(im.remote && im.remote.src)) problems.push(where + ": PUBLISHED without image.acquired and not a linked image"); continue; }
      if (!exists(a.file)) { problems.push(where + ": image file missing " + a.file); continue; }
      const f = ED.fileFacts(a.file);
      if (f.bytes !== a.bytes) problems.push(where + ": size " + f.bytes + " != recorded " + a.bytes);
      if (f.sha256 !== a.sha256) problems.push(where + ": sha256 mismatch");
      if (f.width !== a.width || f.height !== a.height) problems.push(where + ": pixel size " + f.width + "x" + f.height + " != recorded " + a.width + "x" + a.height);
      const op = im.ownerPhoto;
      if (op) {
        const p = photos[op.photoId];
        if (!p) { problems.push(where + ": ownerPhoto " + op.photoId + " is not in photo-library.json"); continue; }
        if (p.files.card !== a.file) problems.push(where + ": ownerPhoto card file differs from the library");
        // A photo from the owner's Apple Photos library is identified by its Apple Photos id; a photo supplied from elsewhere (for example a
        // venue's own image) is identified by the sha256 of the supplied file, which is kept in the library entry.
        const oid = p.original && (p.original.apple_photos_uuid || p.original.sha256);
        if (!p.original || !p.original.filename || !oid) problems.push(where + ": library lacks the original photo identifiers for " + op.photoId);
        else if (op.photoId.slice(5, 13).toUpperCase() !== oid.slice(0, 8).toUpperCase()) problems.push(where + ": photoId does not match the original photo identifier");
        if (op.authorization.statement !== p.license) problems.push(where + ": authorization statement differs from the library");
        if (op.reviewRef !== p.review_ref) problems.push(where + ": reviewRef differs from the library");
        if (im.licenseUrl) problems.push(where + ": owner photo must not carry a licenseUrl (owner authorization is not a Creative Commons license)");
      }
    }
  }
  return problems;
}

const check = process.argv.includes("--check");
if (require.main === module) {
  const problems = validateAssets();
  if (problems.length) { console.error("asset validation failed:\n" + problems.join("\n")); process.exit(1); }
}
// Owner decision 2026-10-20: report-first expiration. The build fails ONLY for a verified-ended entry that is still PUBLISHED with no
// editorial disposition. Missing or uncertain end dates never fail the build and never hide anything.
if (require.main === module) {
  const X = require("../api/_lib/seasonal-editorial/expiration.js");
  const rep = X.expirationReport(ED.entries(), X.detroitToday());
  if (rep.failures.length) { console.error("seasonal expiration: verified-ended entries still published without a disposition:\n" + rep.failures.join("\n")); process.exit(1); }
}
let stale = [];
if (require.main === module) {
  const pub = path.join(root, PUBLISHED_FILE), src = publishedSource();
  if (check) { if (!fs.existsSync(pub) || fs.readFileSync(pub, "utf8") !== src) stale.push(PUBLISHED_FILE); }
  else fs.writeFileSync(pub, src);
  const projection = ED.publishedProjection();
  // The pages are rendered against the projection computed now, not whatever published-entries.js was loaded when this
  // process started: load the renderer fresh with the projection injected, so a first build after an approval is complete.
  const fresh = (() => {
    const pubPath = require.resolve("../seasonal/published-entries.js");
    ["collections.js", "render.js", "published-entries.js"].forEach((f) => { delete require.cache[require.resolve("../seasonal/" + f)]; });
    require.cache[pubPath] = { id: pubPath, filename: pubPath, loaded: true, exports: projection, children: [], paths: [] };
    const r = require("../seasonal/render.js");
    return r;
  })();
  for (const slug of ED.COLLECTIONS.ORDER) {
    const out = path.join(root, FILES[slug]);
    const html = page(Object.assign({}, ED.COLLECTIONS.COLLECTIONS[slug], { entries: projection[slug] }), fresh);
    if (check) { if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== html) stale.push(FILES[slug]); }
    else fs.writeFileSync(out, html);
  }
  if (check && stale.length) { console.error("stale: " + stale.join(", ")); process.exit(1); }
}
module.exports = { page, FILES, validateAssets, publishedSource, PUBLISHED_FILE };
