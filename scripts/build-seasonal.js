#!/usr/bin/env node
// scripts/build-seasonal.js — writes fall.html, halloween.html, fall-color.html
// and seasonal/published-entries.js from the private editorial data
// (api/_lib/seasonal-editorial/entries.json) via seasonal/collections.js and seasonal/render.js. Only entries that
// pass the whole publication gate are copied into published-entries.js; nothing else is public. Output is committed
// so the pages are static and crawlable; seasonal/page.js only enhances them.
//   node scripts/build-seasonal.js          write files
//   node scripts/build-seasonal.js --check  exit 1 if committed files are stale or an asset fails validation
"use strict";
const fs = require("fs");
const path = require("path");
const ED = require("../api/_lib/seasonal-editorial/editorial.js");
const RENDER = require("../seasonal/render.js");
const root = path.join(__dirname, "..");
const PUBLISHED_FILE = "seasonal/published-entries.js";

// The public projection file. Entries are exactly those that are declared and derived PUBLISHED.
function publishedSource() {
  return `/* seasonal/published-entries.js — GENERATED by scripts/build-seasonal.js. Do not edit by hand.
 *
 * The only destination records served publicly: entries whose status is PUBLISHED and that pass every publication
 * gate item (see seasonal/collections.js). Every other record, including unpublished destinations, image candidates,
 * rights metadata and review evidence, stays in the private editorial data (api/_lib/seasonal-editorial/).
 * Empty until an entry has the explicit publication approval (gate item 5).
 */
(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.SeasonalPublishedEntries = factory();
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";
  return ${JSON.stringify(ED.publishedProjection())};
});
`;
}
const FILES = { fall: "fall.html", halloween: "halloween.html", "fall-color": "fall-color.html" };

